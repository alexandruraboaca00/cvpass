import type { EditorProfileView } from './profile-editor.js';
import type { ProfileSelection } from './profile-selection.js';
import type { EditorLibraryView, EditorDocumentView, PhotoView } from './editor.js';
import type { EditorForm, ProfileEditorForm, EditorIssue, EditorTarget } from './editor-model.js';
import type { SectionKind } from '../domain/index.js';
import type { ImportView, ImportReviewInput } from './structured-import.js';
import type { PdfGeneration, PresentationInput } from './render-contract.js';
import type { ExportRecord } from './export-record.js';
export type BeginEditorTarget=EditorTarget|{kind:'newEntry';sectionId:string;entryKind?:'nativeLanguage'|'foreignLanguage'}|{kind:'newCustomSection'};
export interface EditorFailure {code:string;issues:EditorIssue[]}
export type EditorResult<T> = {ok:true;value:T}|{ok:false;error:EditorFailure};
export interface EditorApi {
  workspaceExport():Promise<EditorResult<{cancelled:boolean;sha256?:string;byteLength?:number}>>;
  profileOpen():Promise<EditorResult<EditorProfileView>>;
  profileCreate(name:string):Promise<EditorResult<EditorProfileView>>;
  profileMaterialize(name:string,locale:'es'|'en',revision:number,selection:ProfileSelection):Promise<EditorResult<EditorDocumentView>>;
  profileAddSection(revision:number,kind:Exclude<SectionKind,'custom'>):Promise<EditorResult<EditorProfileView>>;
  profileBegin(revision:number,target:BeginEditorTarget,textLocale:'es'|'en'):Promise<EditorResult<ProfileEditorForm>>;
  profileStage(form:ProfileEditorForm):Promise<EditorResult<void>>;
  profileConfirm(form:ProfileEditorForm):Promise<EditorResult<EditorProfileView>>;
  profileCancel():Promise<EditorResult<EditorProfileView>>;
  profilePhoto(bytes:Uint8Array,mediaType:'image/png'|'image/jpeg'):Promise<EditorResult<{form:ProfileEditorForm;photo:PhotoView}>>;
  profileRecover(id:string):Promise<EditorResult<{form:ProfileEditorForm;photo:PhotoView|null}>>;
  profileRemove(revision:number,sectionId:string,entryId:string|null,confirm:true):Promise<EditorResult<EditorProfileView>>;
  profileRevisions():Promise<EditorResult<{id:string;number:number;cause:string;pinned:boolean}[]>>;
  profileRestore(revision:number,id:string):Promise<EditorResult<EditorProfileView>>;
  projectExport(cvId:string,revision:number):Promise<EditorResult<{cancelled:boolean;sha256?:string;byteLength?:number}>>;
  pdfRecords(cvId:string):Promise<EditorResult<ExportRecord[]>>;
  pdfGenerate(cvId:string,revision:number):Promise<EditorResult<PdfGeneration>>;
  pdfCancel():Promise<EditorResult<void>>;
  pdfOpenLink(url:string):Promise<EditorResult<void>>;
  pdfExport(id:string,digest:string):Promise<EditorResult<{cancelled:boolean;sha256?:string;byteLength?:number;revision?:number}>>;
  presentation(cvId:string,revision:number,input:PresentationInput):Promise<EditorResult<EditorDocumentView>>;
  importFile(id:string,bytes:Uint8Array,fileName:string):Promise<EditorResult<ImportView>>;
  importChoose(id:string,key:string):Promise<EditorResult<ImportView>>;
  importCancel(id:string):Promise<EditorResult<void>>;
  importConfirm(id:string,input:ImportReviewInput):Promise<EditorResult<{cvId:string}>>;
  importRestore(id:string,mode:'emptyWorkspace'|'replaceWorkspace',confirmReplace:boolean):Promise<EditorResult<{backup?:{name:string}}>>;
  importPhoto(id:string,bytes:Uint8Array,mediaType:'image/png'|'image/jpeg'):Promise<EditorResult<{assetId:string;photo:PhotoView}>>;
  list():Promise<EditorResult<EditorLibraryView>>;
  create(name:string,displayName:string):Promise<EditorResult<EditorDocumentView>>;
  open(id:string):Promise<EditorResult<EditorDocumentView>>;
  setUiLocale(locale:'es'|'en'):Promise<EditorResult<EditorLibraryView>>;
  duplicate(cvId:string,revision:number,name:string):Promise<EditorResult<EditorDocumentView>>;
  revisions(cvId:string):Promise<EditorResult<{id:string;number:number;cause:string;pinned:boolean}[]>>;
  restore(cvId:string,revision:number,checkpointId:string):Promise<EditorResult<EditorDocumentView>>;
  addSection(cvId:string,revision:number,kind:Exclude<SectionKind,'custom'>):Promise<EditorResult<EditorDocumentView>>;
  begin(cvId:string,revision:number,target:BeginEditorTarget):Promise<EditorResult<EditorForm>>;
  stage(form:EditorForm):Promise<EditorResult<void>>;
  confirm(form:EditorForm):Promise<EditorResult<EditorDocumentView>>;
  cancel():Promise<EditorResult<EditorDocumentView>>;
  photo(bytes:Uint8Array,mediaType:'image/png'|'image/jpeg'):Promise<EditorResult<{form:EditorForm;photo:PhotoView}>>;
  visibility(cvId:string,revision:number,sectionId:string,entryId:string|null,included:boolean):Promise<EditorResult<EditorDocumentView>>;
  remove(cvId:string,revision:number,sectionId:string,entryId:string|null,confirm:true):Promise<EditorResult<EditorDocumentView>>;
  recover(id:string):Promise<EditorResult<{form:EditorForm;photo:PhotoView|null}>>;
  discardRecovery(id:string):Promise<EditorResult<EditorLibraryView>>;
  status():Promise<EditorResult<{status:string;error:boolean}>>;
  flush():Promise<EditorResult<void>>;
  close():Promise<EditorResult<void>>;
  onCloseRequested(callback:()=>void):()=>void;
}
