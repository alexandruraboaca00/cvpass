  await assert.rejects(library.importCvproj(bytes,{mode:'emptyWorkspace'}),/WORKSPACE_NOT_EMPTY/);
  await assert.rejects(library.importCvproj(bytes,{mode:'replaceWorkspace'}),/REPLACE_CONFIRMATION_REQUIRED/);
