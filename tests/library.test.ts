  current.personalInformation.photo = {assetId:asset.id,crop:{x:0,y:0,width:1,height:1},visible:true};
  const saved = await library.confirmEntity(current,current.revision,{assetsById:{[asset.id]:asset},blobs:new Map([[asset.sha256,newBytes]])});
